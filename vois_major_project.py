"""**Outlier Investigation using Interquartile Range (IQR)**"""

numeric_cols = ['Yield_Tonnes_Ha', 'Total_Cost_INR', 'Profit_INR', 'Rainfall_mm']

for col in numeric_cols:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR
    outliers = df[(df[col] < lower_bound) | (df[col] > upper_bound)]
    print(f"{col}: Found {len(outliers)} potential outliers (Out of {len(df)} rows)")

# Visualize outliers with boxplots
plt.figure(figsize=(12, 5))
plt.subplot(1, 2, 1)
sns.boxplot(y=df['Yield_Tonnes_Ha'], color='skyblue')
plt.title('Yield Outlier Distribution')

plt.subplot(1, 2, 2)
sns.boxplot(y=df['Profit_INR'], color='salmon')
plt.title('Profit Outlier Distribution')
plt.tight_layout()
plt.show()

# Define key numerical columns to analyze for outliers
num_cols = ['Yield_Tonnes_Ha', 'Total_Cost_INR', 'Profit_INR', 'Rainfall_mm', 'Fertilizer_kg_ha', 'Water_Used_m3']
outlier_summary = []

for col in num_cols:
    series = df[col].dropna()
    Q1 = series.quantile(0.25)
    Q3 = series.quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    # Identify outliers beyond the 1.5 * IQR bounds
    outliers = series[(series < lower_bound) | (series > upper_bound)]

    outlier_summary.append({
        'Metric / Column': col,
        'Q1 (25%)': round(Q1, 2),
        'Q3 (75%)': round(Q3, 2),
        'IQR': round(IQR, 2),
        'Lower Bound': round(lower_bound, 2),
        'Upper Bound': round(upper_bound, 2),
        'Outlier Count': len(outliers),
        'Outlier %': round((len(outliers) / len(series)) * 100, 2)
    })

# Convert to DataFrame for neat display
outlier_df = pd.DataFrame(outlier_summary)
display(outlier_df)

