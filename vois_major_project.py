"""**Cost-to-Profit Quadrant Analysis & Return on Investment (ROI) Distribution**"""

# Calculate ROI percentage if it doesn't already exist in the dataframe
df['ROI_pct'] = (df['Profit_INR'] / df['Total_Cost_INR']) * 100

# Set up the figure dimensions
plt.figure(figsize=(10, 6))

# Create a scatter plot mapping Total Cost vs. Profit, colored and sized by ROI
scatter = sns.scatterplot(
    data=df,
    x='Total_Cost_INR',
    y='Profit_INR',
    hue='ROI_pct',
    palette='coolwarm',
    alpha=0.8,
    s=60
)

# Add quadrant reference lines at zero profit and median cost
