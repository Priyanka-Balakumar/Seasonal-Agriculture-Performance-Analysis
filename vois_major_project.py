import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Load the dataset
df = pd.read_csv('/content/seasonal_agriculture_performance_dataset (1).csv')

"""**Review top and bottom rows**"""

display(df.head())
display(df.tail())

"""**Check dimensions, column names, and data types**"""

print("Shape:", df.shape)
print("\nColumns:")
print(df.columns.to_list())
df.info()

"""**Comprehensive statistical summary**"""

df.describe(include='all').T

"""**Check for duplicate rows and missing values before cleaning**"""

duplicate_count = df.duplicated().sum()
print(f"Duplicate Rows: {duplicate_count}")

missing = pd.DataFrame({
    'Missing Count': df.isna().sum(),
    'Missing %': (df.isna().mean() * 100).round(2)
})
display(missing[missing['Missing Count'] > 0].sort_values('Missing Count', ascending=False))

"""# Data Cleaning & Imputation Strategy
**Impute numerical missing values with median and Verify missing values after cleaning**


"""

for col in ['Rainfall_mm', 'Soil_Moisture_pct', 'Yield_Tonnes_Ha']:
    if col in df.columns:
        df[col] = df[col].fillna(df[col].median())

print("Missing values remaining:", df.isna().sum().sum())

