crop_summary = df.groupby('Crop').agg({
    'Production_Tonnes': 'sum',
    'Yield_Tonnes_Ha': 'mean',
    'Profit_INR': 'mean',
    'Water_Efficiency_t_per_1000m3': 'mean'
}).reset_index()

display(crop_summary)

